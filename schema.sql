PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS orders(id TEXT PRIMARY KEY,status TEXT NOT NULL,data TEXT NOT NULL,created INTEGER NOT NULL,updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS attempts(nonce TEXT PRIMARY KEY,order_id TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS disabled(asset TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS audit(at INTEGER NOT NULL,event TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS orders_status ON orders(status,updated);
